def defv(v, m):
    dv = v.get('default')
    if dv is None: return ''
    if dv == 'GUID': return ' = Guid.NewGuid().ToString("N");'
    if dv in ('true','false'): return f' = {dv};'
    if dv == 'null': return ''
    mm = re.fullmatch(r"'(.*)'", dv)
    if mm:
        if m == 'string': return ' = ' + json.dumps(mm.group(1)) + ';'
        return ''
    if re.fullmatch(r'-?\d+(\.\d+)?', dv):
        if m == 'decimal': return f' = {dv}m;'
        if m in ('int','long'): return f' = {dv};'
        if m == 'bool': return f' = {"true" if dv != "0" else "false"};'
    return ''

